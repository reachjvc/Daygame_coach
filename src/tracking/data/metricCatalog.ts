/**
 * Everything the app can currently count, described well enough to put in a
 * picker.
 *
 * WHAT BELONGS HERE: a metric appears in this file only if something already
 * produces the number — a session write, a health log, a scenario run. There is
 * no entry for a thing we would like to track one day. A metric with no source
 * would render as a permanent "—", which teaches the user the dashboard is
 * decorative.
 *
 * COVERAGE RULE, enforced by tests/unit/tracking/metricCatalog.test.ts: every
 * value in LINKED_METRICS has an entry, so a goal's linked_metric always names
 * something describable. The reverse does not hold — entries with
 * `linkedMetric: null` (week streak, unique locations) are display-only, because
 * nothing syncs them into a goal's current_value.
 *
 * WHAT IS DELIBERATELY ABSENT: Career & Finances, Personal Growth and Vices have
 * no entries. Not an oversight — the app has no career, journalling or
 * abstinence data source yet. Goals in those areas are tracked through
 * goal-derived metrics (metricsService), where the goal's own logged value is
 * the source. That is why "deep work" is trackable without a deep-work table.
 *
 * ICONS: registered in src/shared/iconRoles.ts. `accent` is the icon colour.
 * The first four entries below carry the colours the dashboard shipped with, so
 * the default layout looks unchanged.
 */

