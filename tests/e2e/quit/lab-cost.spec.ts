/**
 * THE COST AND SAVINGS COPIES, WALKED ON A PHONE.
 *
 * Signed out, 390x844, dark: one test per copy (b, c, e) walks every seen screen of its spec in
 * order, types inputs and checks that the totals and goal progress move. Each screen is shot into
 * ~/.cache/daygame-research/quit-copy/cost/shots-ours/<letter>/.
 * Everything lives in this browser's storage, so nothing is written to the live database.
 */

import { mkdirSync, rmSync } from "node:fs"
import { homedir } from "node:os"
import path from "node:path"
import { test, expect, SIGNED_OUT } from "../fixtures/test"
import type { Page } from "@playwright/test"

test.use({ storageState: SIGNED_OUT, viewport: { width: 390, height: 844 }, colorScheme: "dark" })

const SHOTS = path.join(homedir(), ".cache/daygame-research/quit-copy/cost/shots-ours")
const DAY = 86_400_000

let n = 0
async function shot(page: Page, letter: string, name: string) {
  n += 1
  if (letter === "e" && (await page.getByTestId("e-month").count()) > 0 && (await page.getByTestId("e-month").isVisible())) await settled(page)
  const dir = path.join(SHOTS, letter)
  mkdirSync(dir, { recursive: true })
  await page.addStyleTag({ content: "nextjs-portal{display:none !important}" })
  await page.screenshot({ path: path.join(dir, `${String(n).padStart(2, "0")}-${name}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
}

async function open(page: Page, letter: string) {
  n = 0
  rmSync(path.join(SHOTS, letter), { recursive: true, force: true })
  const errors: string[] = []
  page.on("pageerror", (e) => errors.push(e.message))
  const res = await page.goto(`/quit/lab/cost/${letter}?preview=1`)
  expect(res?.status()).toBe(200)
  await expect(page.getByTestId(`cost-${letter}`)).toBeVisible()
  return errors
}

const local = (ms: number) => {
  const d = new Date(ms)
  const p = (x: number) => String(x).padStart(2, "0")
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}`
}
const val = async (page: Page, id: string, attr = "data-value") => Number(await page.getByTestId(id).first().getAttribute(attr))
/** The big per-month figure counts up for half a second; wait until it shows what the tile says. */
async function settled(page: Page) {
  const v = Number(await page.getByTestId("e-month").getAttribute("data-value"))
  const want = `$${v < 100 ? v.toFixed(2) : Math.round(v).toLocaleString("en-US")}`
  await expect(page.getByTestId("e-month")).toHaveText(want)
  await expect(page.getByTestId("e-flame-sign")).toHaveText(want)
}
const near = (x: number, target: number, tol: number) => expect(Math.abs(x - target)).toBeLessThanOrEqual(tol)

