/**
 * THE DAILY CHECK-IN COPIES, WALKED ON A PHONE.
 *
 * Signed out, 390x844, dark: one test per copy (a to d) opens the copy on its example data
 * (14 days) and walks every screen of its spec in order, including a full check-in that then
 * shows in the history of that copy. Each screen is shot into
 * ~/.cache/daygame-research/quit-copy/checkin/shots-ours/<letter>/. Everything lives in this
 * browser's storage, so nothing is written to the live database.
 */

import { mkdirSync } from "node:fs"
import { homedir } from "node:os"
import path from "node:path"
import { test, expect, SIGNED_OUT } from "../fixtures/test"
import type { Page } from "@playwright/test"

test.use({ storageState: SIGNED_OUT, viewport: { width: 390, height: 844 }, colorScheme: "dark" })

const SHOTS = path.join(homedir(), ".cache/daygame-research/quit-copy/checkin/shots-ours")

const keyOf = (offset: number) => {
  const d = new Date()
  d.setDate(d.getDate() + offset)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`
}
const TODAY = () => keyOf(0)

async function start(page: Page, letter: string) {
  const errors: string[] = []
  page.on("pageerror", (e) => errors.push(e.message))
  const res = await page.goto(`/quit/lab/checkin/${letter}?preview=1`)
  expect(res?.status()).toBe(200)
  await expect(page.getByTestId(`checkin-${letter}`)).toBeVisible()
  await expect(page.getByTestId("example-bar")).toBeVisible()
  return errors
}

let n = 0
async function shot(page: Page, letter: string, name: string) {
  n += 1
  const dir = path.join(SHOTS, letter)
  mkdirSync(dir, { recursive: true })
  await page.addStyleTag({ content: "nextjs-portal{display:none !important}" })
  await page.screenshot({ path: path.join(dir, `${String(n).padStart(2, "0")}-${name}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
}

const back = (page: Page) => page.getByTestId("screen-back").click()
const tid = (page: Page, id: string) => page.getByTestId(id)

/** Every 44px rule: visible buttons on the screen are at least 44 px tall (inline text links aside). */
async function tapsBigEnough(page: Page) {
  const small = await page.evaluate(() =>
    Array.from(document.querySelectorAll("button, input, select, textarea"))
      .filter((el) => {
        const r = (el as HTMLElement).getBoundingClientRect()
        return r.width > 0 && r.height > 0 && r.height < 40 && !(el as HTMLElement).closest("[data-testid='checkin-c'] [role=progressbar]")
      })
      .map((el) => `${el.tagName}:${(el.textContent ?? "").slice(0, 20)}`),
  )
  expect(small).toEqual([])
}

