  await page.mouse.down()
  await expect(page.getByTestId("face")).toHaveAttribute("data-held", "true")
  await expect(page.getByTestId("breathe-text")).toHaveText("Breathe out slowly")
  await shot("breathe-holding")
  await page.mouse.up()
