  for (const i of [1, 2]) {
    await page.getByTestId(`discover-tab-${i}`).click()
    await expect(page.getByTestId("placeholder").first()).toBeVisible()
    await shot(`discover-tab-${i}-inferred`)
  }
  await page.getByTestId("discover-tab-3").click()
  await shot("discover-cravings-inferred")
  await page.getByTestId("cravings-breathe").click()
