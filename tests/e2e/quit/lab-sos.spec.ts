  const head = page.getByTestId("snake-head")
  await expect(page.getByTestId("time")).toHaveText("03:00")
  // the fake clock makes the game's pace exact: pause holds everything, resume moves it
  await page.getByTestId("pause").click()
  const frozenX = await head.getAttribute("x")
  await page.clock.runFor(2000)
  expect(await head.getAttribute("x")).toBe(frozenX)
  await expect(page.getByTestId("time")).toHaveText("03:00")
  await shot("snake-paused")
  await page.getByTestId("pause").click()
  await page.getByTestId("dpad-up").click()
  await page.clock.runFor(450)
  await expect(head).toHaveAttribute("y", "5.05")
  await page.getByTestId("dpad-right").click()
  await page.clock.runFor(600)
  await expect(page.getByTestId("time")).toHaveText("02:59")
  await shot("snake-playing")
  // the right wall ends the run
  await page.clock.runFor(5000)
  await expect(page.getByTestId("snake-result")).toBeVisible()
  await expect(page.getByTestId("inferred-tag")).toBeVisible()
  await shot("snake-result-inferred")
  await page.getByTestId("play-again").click()
  await expect(page.getByTestId("snake")).toBeVisible()
  await page.getByTestId("snake-back").click()

  await page.getByTestId("tab-3").click()
  await expect(page.getByTestId("discover-card")).toBeVisible()
