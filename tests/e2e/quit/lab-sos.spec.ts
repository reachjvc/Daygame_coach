/**
 * THE CRAVING SOS COPIES, WALKED ON A PHONE.
 *
 * Signed out, 390x844, one test per copy: tap through every screen of the copy in the order of its
 * spec, check the moving parts (countdown, games, hold-to-breathe, pie), and save a phone screenshot
 * of each screen outside the repo. State lives in the browser (`quit-lab-v1`); nothing is written to
 * the database.
 */

import { mkdirSync } from "node:fs"
import { homedir } from "node:os"
import path from "node:path"
import type { Page } from "@playwright/test"
import { test, expect, SIGNED_OUT } from "../fixtures/test"

test.use({ storageState: SIGNED_OUT, viewport: { width: 390, height: 844 } })

const SHOTS = path.join(homedir(), ".cache/daygame-research/quit-copy/sos/shots-ours")

function shooter(page: Page, letter: string) {
  const dir = path.join(SHOTS, letter)
  mkdirSync(dir, { recursive: true })
  let n = 0
  return async (name: string) => {
    n++
    await page.screenshot({ path: path.join(dir, `${String(n).padStart(2, "0")}-${name}.png`) })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  }
}

const open = (page: Page, letter: string) => page.goto(`/quit/lab/sos/${letter}?preview=1`)

