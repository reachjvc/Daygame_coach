/**
 * THE QUIT DATE AND PLAN COPIES, WALKED ON A PHONE.
 *
 * Signed out, 390x844, dark: one test per copy (a, b, d, e) opens the copy and walks every
 * seen screen of its spec in order. Screens that were never seen carry the inferred tag; every
 * competitor figure without a source reads "number not sourced yet"; payment and account steps
 * read "not copied". Each screen is shot into
 * ~/.cache/daygame-research/quit-copy/quitdate/shots-ours/<letter>/. Everything lives in this
 * browser's storage, so the test writes nothing to the live database.
 */

import { mkdirSync } from "node:fs"
import { homedir } from "node:os"
import path from "node:path"
import { test, expect, SIGNED_OUT } from "../fixtures/test"
import type { Page } from "@playwright/test"

test.use({ storageState: SIGNED_OUT, viewport: { width: 390, height: 844 }, colorScheme: "dark" })

const SHOTS = path.join(homedir(), ".cache/daygame-research/quit-copy/quitdate/shots-ours")

async function start(page: Page, letter: string) {
  const errors: string[] = []
  page.on("pageerror", (e) => errors.push(e.message))
  const res = await page.goto(`/quit/lab/quitdate/${letter}?preview=1`)
  expect(res?.status()).toBe(200)
  await expect(page.getByTestId(`quitdate-${letter}`).or(page.getByTestId("setup-choice"))).toBeVisible()
  return errors
}

let n = 0
async function shot(page: Page, letter: string, name: string) {
  n += 1
  const dir = path.join(SHOTS, letter)
  mkdirSync(dir, { recursive: true })
  await page.addStyleTag({ content: "nextjs-portal{display:none !important}" })
  await page.screenshot({ path: path.join(dir, `${String(n).padStart(2, "0")}-${name}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
}

const text = (page: Page, id: string) => page.getByTestId(id).innerText()
const back = (page: Page) => page.getByTestId("screen-back").click()

test.beforeEach(() => {
  n = 0
})

