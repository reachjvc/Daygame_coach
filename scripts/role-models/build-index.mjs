#!/usr/bin/env node
/**
 * Writes src/role-models/data/index.generated.ts from the person files.
 *
 * Static imports, sorted by id, so the catalogue is bundled at build time and no
 * page reads the file system. Run after adding or renaming a person file:
 *   node scripts/role-models/build-index.mjs
 * A unit test fails when the index and the folder disagree.
 */
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const dir = join(root, "src/role-models/data/people")
const ids = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.slice(0, -5))
  .sort()

const ident = (id) => "p_" + id.replace(/[^a-z0-9]/g, "_")
const lines = [
  "// GENERATED by scripts/role-models/build-index.mjs. Do not edit; run the script.",
  'import type { RoleModelPerson } from "../types"',
  "",
  ...ids.map((id) => `import ${ident(id)} from "./people/${id}.json"`),
  "",
  `export const PERSON_IDS = ${JSON.stringify(ids)} as const`,
  "",
  `export const PEOPLE = [${ids.map(ident).join(", ")}] as unknown as RoleModelPerson[]`,
  "",
]
writeFileSync(join(root, "src/role-models/data/index.generated.ts"), lines.join("\n"))
console.log(`index: ${ids.length} people`)
